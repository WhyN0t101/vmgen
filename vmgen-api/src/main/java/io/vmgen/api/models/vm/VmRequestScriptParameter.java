package io.vmgen.api.models.vm;

import io.vmgen.api.models.script.Script;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.Id;
import jakarta.persistence.IdClass;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import lombok.Data;

/**
 * Concrete value for a given script parameter within the context of a
 * particular VM request.
 */
@Entity
@Table(name = "vm_request_script_parameters")
@IdClass(VmRequestScriptParameterId.class)
@Data
public class VmRequestScriptParameter {

    @Id
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "vm_request_id", nullable = false)
    private VmRequest vmRequest;

    @Id
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "script_id", nullable = false)
    private Script script;

    @Id
    @Column(name = "parameter_name", nullable = false, length = 100)
    private String parameterName;

    @Column(name = "parameter_value", nullable = false, columnDefinition = "TEXT")
    private String parameterValue;

    @Column(name = "was_auto_generated", nullable = false)
    private Boolean wasAutoGenerated = Boolean.FALSE;
}

