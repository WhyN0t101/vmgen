package io.vmgen.api.dto.build;

import jakarta.validation.constraints.NotEmpty;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Pattern;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import lombok.Data;

@Data
public class CreateBuildRequest {

    @NotNull(message = "templateId is required")
    private UUID templateId;

    @NotNull(message = "vulnerabilityIds is required")
    @NotEmpty(message = "At least one script must be selected")
    private List<UUID> vulnerabilityIds;

    @NotNull(message = "difficulty is required")
    @Pattern(regexp = "^(easy|medium|hard)$", message = "difficulty must be easy, medium, or hard")
    private String difficulty;

    private boolean telemetryEnabled = false;

    /**
     * User-provided parameter values: scriptId (as string) → paramName → value.
     * Only USER_INPUT parameters are expected here; USER_INPUT_OR_RANDOM params without
     * a provided value will be auto-generated by the service.
     */
    private Map<String, Map<String, String>> scriptParameters;
}
